    [Fact]
    public void BuildAlterTableScript_SqLite_IndexChange_TriggersFullRebuild()
    {
        var original = BuildBasicTable(DatabaseType.SqLite);
        original.Columns[0].OriginalName = original.Columns[0].Name;
        original.Indexes.Add(new TableIndexDefinition { Name = "IX_Orders_Id" });
        original.Indexes[0].Columns.Add(new TableIndexColumnDefinition { Name = "Id" });
        var current = BuildBasicTable(DatabaseType.SqLite);
        current.Columns[0].OriginalName = original.Columns[0].Name;
        // current drops the index without touching columns; SQLite has no DROP INDEX-only ALTER
        // shortcut in this builder's model, so any structural change triggers the full rebuild.

        var sql = TableDdlScriptBuilder.BuildAlterTableScript(DatabaseType.SqLite, original, current);

        Assert.Contains("pragma foreign_keys=off;", sql);
        Assert.Contains("create table \"temp_Orders\"", sql);
        Assert.Contains("insert into \"temp_Orders\" (\"Id\") select \"Id\" from \"Orders\";", sql);
        Assert.Contains("drop table \"Orders\";", sql);
        Assert.Contains("alter table \"temp_Orders\" rename to \"Orders\";", sql);
        Assert.Contains("pragma foreign_keys=on;", sql);
        Assert.DoesNotContain("create index \"IX_Orders_Id\"", sql);
    }

