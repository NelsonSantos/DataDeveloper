        var index = new TableIndexDefinition { Name = "IX_Orders_Id" };
        var indexColumn = new TableIndexColumnDefinition { Name = "Id" };
        indexColumn.ProviderOptions["prefix_length"] = "10";
        index.Columns.Add(indexColumn);
        current.Indexes.Add(index);

        var sql = TableDdlScriptBuilder.BuildAlterTableScript(DatabaseType.MySql, original, current);

        Assert.Equal(
            "create index `IX_Orders_Id`\n    on `Orders` (`Id`(10));",
            sql);
    }

    [Fact]
    public void BuildAlterTableScript_UneditedDecimalColumn_WithSpuriousLoadedLength_GeneratesNoStatements()
    {
        // Regression test: some providers report a non-zero internal storage size for a
        // column's "Length" even when the type has no length concept at all (for example SQL
        // Server's sys.columns.max_length is non-zero for decimal columns) — that value used to
        // be compared directly against "current" (always null for a type that doesn't support
        // Length), making every untouched decimal/datetime2/uniqueidentifier/etc. column look
        // like it had been retyped as soon as the edit-table designer opened.
        var original = BuildBasicTable();
        original.Columns[0].OriginalName = original.Columns[0].Name;
        original.Columns.Add(new TableColumnDefinition
        {
            OriginalName = "Total",
            Name = "Total",
            DataType = "decimal",
            Precision = 18,
            Scale = 2,
            Length = 9, // spurious storage-size value a loader could report for this type
            IsNullable = false
        });

        var current = BuildBasicTable();
        current.Columns[0].OriginalName = original.Columns[0].Name;
        current.Columns.Add(new TableColumnDefinition
        {
            OriginalName = "Total",
            Name = "Total",
            DataType = "decimal",
            Precision = 18,
            Scale = 2,
            Length = null,
            IsNullable = false
        });

        var sql = TableDdlScriptBuilder.BuildAlterTableScript(DatabaseType.SqlServer, original, current);

        Assert.Equal(string.Empty, sql);
    }

    private static TableDefinition BuildTableWithCodeColumn(DatabaseType databaseType, int length, bool isNullable)
    {
        var table = BuildBasicTable(databaseType);
        table.Columns.Add(new TableColumnDefinition
        {
            Name = databaseType == DatabaseType.Oracle ? "CODE" : "Code",
            DataType = databaseType == DatabaseType.Oracle ? "varchar2" : databaseType == DatabaseType.SqlServer ? "nvarchar" : "varchar",
            Length = length,
            IsNullable = isNullable
        });
        return table;
    }

    private static TableDefinition BuildBasicTable(DatabaseType databaseType = DatabaseType.SqlServer)
    {
        var table = new TableDefinition
        {
            SchemaName = databaseType == DatabaseType.SqlServer ? "dbo" : string.Empty,
            TableName = databaseType == DatabaseType.Oracle ? "ORDERS" : "Orders"
        };
        table.Columns.Add(new TableColumnDefinition
        {
            Name = databaseType == DatabaseType.Oracle ? "ID" : "Id",
            DataType = databaseType == DatabaseType.Oracle ? "number" : "int",
            IsNullable = false,
            IsIdentity = true
        });
        table.PrimaryKey.Name = databaseType == DatabaseType.Oracle ? "PK_ORDERS" : "PK_Orders";
        table.PrimaryKey.ColumnNames.Add(databaseType == DatabaseType.Oracle ? "ID" : "Id");
        return table;
    }
