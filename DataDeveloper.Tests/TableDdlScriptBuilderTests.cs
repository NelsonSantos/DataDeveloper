    [Fact]
    public void BuildCreateTableScript_GeneratesSqlServerTableWithConstraintsAndIndex()
    {
        var table = new TableDefinition
        {
            SchemaName = "dbo",
            TableName = "Orders"
        };
        table.Columns.Add(new TableColumnDefinition
        {
            Name = "Id",
            DataType = "int",
            IsNullable = false,
            IsIdentity = true
        });
        table.Columns.Add(new TableColumnDefinition
        {
            Name = "CustomerId",
            DataType = "int",
            IsNullable = false
        });
        table.Columns.Add(new TableColumnDefinition
        {
            Name = "Code",
            DataType = "nvarchar",
            Length = 50,
            IsNullable = false,
            DefaultValue = "N''"
        });
        table.PrimaryKey.Name = "PK_Orders";
        table.PrimaryKey.ColumnNames.Add("Id");
        table.ForeignKeys.Add(new TableForeignKeyDefinition
        {
            Name = "FK_Orders_Customers",
            ReferencedSchemaName = "dbo",
            ReferencedTableName = "Customers",
            OnDeleteAction = "cascade",
            OnUpdateAction = "no action"
        });
        table.ForeignKeys[0].ColumnNames.Add("CustomerId");
        table.ForeignKeys[0].ReferencedColumnNames.Add("Id");
        table.Indexes.Add(new TableIndexDefinition
        {
            Name = "IX_Orders_CustomerId"
        });
        table.Indexes[0].Columns.Add(new TableIndexColumnDefinition { Name = "CustomerId" });

        var sql = TableDdlScriptBuilder.BuildCreateTableScript(DatabaseType.SqlServer, table);

        Assert.Equal(
            """
            create table [dbo].[Orders]
            (
                [Id] int identity(1, 1) not null,
                [CustomerId] int not null,
                [Code] nvarchar(50) not null default N'',
                constraint [PK_Orders] primary key ([Id]),
                constraint [FK_Orders_Customers]
                    foreign key ([CustomerId])
                    references [dbo].[Customers] ([Id])
                    on delete cascade on update no action
            );

            create index [IX_Orders_CustomerId]
                on [dbo].[Orders] ([CustomerId]);
            """,
            sql);
    }

